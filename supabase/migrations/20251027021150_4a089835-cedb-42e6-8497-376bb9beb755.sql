-- Create vertiports table
CREATE TABLE public.vertiports (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  city TEXT NOT NULL,
  state TEXT NOT NULL,
  latitude DECIMAL(10, 7) NOT NULL,
  longitude DECIMAL(10, 7) NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- Create zipcodes table
CREATE TABLE public.zipcodes (
  zipcode TEXT PRIMARY KEY,
  vertiport_id TEXT NOT NULL REFERENCES public.vertiports(id),
  city TEXT,
  borough TEXT,
  latitude DECIMAL(10, 7),
  longitude DECIMAL(10, 7),
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- Enable RLS
ALTER TABLE public.vertiports ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.zipcodes ENABLE ROW LEVEL SECURITY;

-- Public read access for both tables
CREATE POLICY "Anyone can view vertiports"
  ON public.vertiports FOR SELECT
  USING (true);

CREATE POLICY "Anyone can view zipcodes"
  ON public.zipcodes FOR SELECT
  USING (true);

